# Fig 03 - Confusion matrices
# ---------------------------------------------------------------------------
def fig03_confusion_matrices(models, X_test, y_test):
    n = len(models)
    fig, axes = plt.subplots(1, n, figsize=(2.6 * n, 2.6))
    if n == 1:
        axes = [axes]

    for idx, (ax, (name, model)) in enumerate(zip(axes, models.items())):
        y_pred = model.predict(X_test)
        cm = confusion_matrix(y_test, y_pred)
        tn, fp, fn, tp = cm.ravel()
        mat = np.array([[tn, fp], [fn, tp]])

        color = COLORS[name]
        cmap  = mpl.colors.LinearSegmentedColormap.from_list(
            "custom", ["#ffffff", color], N=256
        )
        ax.imshow(mat, cmap=cmap, vmin=0, aspect="auto")

        cell_labels = [["TN", "FP"], ["FN", "TP"]]
        for i in range(2):
            for j in range(2):
                val = mat[i, j]
                text_color = "white" if val > mat.max() * 0.6 else "#333333"
                ax.text(j, i, f"{cell_labels[i][j]}\n{val}",
                        ha="center", va="center", fontsize=8,
                        color=text_color, fontweight="bold")

        ax.set_xticks([0, 1])
        ax.set_yticks([0, 1])
        ax.set_xticklabels(["Neg.", "Pos."], fontsize=7)
        if idx == 0:
            ax.set_yticklabels(["Neg.", "Pos."], fontsize=7)
        else:
            ax.set_yticklabels(["", ""])

        mcc  = matthews_corrcoef(y_test, y_pred)
        acc  = accuracy_score(y_test, y_pred)
        ax.set_title(f"{name}\nAcc={acc:.3f}  MCC={mcc:.3f}", fontsize=8)

    fig.suptitle("Confusion matrices on held-out test set", fontsize=9)
    fig.tight_layout(rect=[0, 0, 1, 0.95])
    savefig(fig, "fig02_confusion_matrices.pdf")


