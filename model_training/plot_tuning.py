# Fig 07 - Top 10 candidates per model
# ---------------------------------------------------------------------------
def fig07_top10_candidates():
    available = {}
    for m in ["rf", "gb", "svm", "xgb"]:
        cv = load_cv_results(m)
        if cv is not None and "mean_test_score" in cv.columns:
            available[m.upper()] = cv

    if not available:
        print("  Skipping fig07: cv_results CSVs not found. Re-run tune.py first.")
        return

    n = len(available)
    ncols = 2
    nrows = (n + 1) // 2
    fig, axes = plt.subplots(nrows, ncols, figsize=(COL2, nrows * 3.0))
    axes = np.array(axes).flatten()

    for idx, (model, cv) in enumerate(available.items()):
        ax = axes[idx]
        color = COLORS[model]
        top10 = cv.nlargest(10, "mean_test_score").reset_index(drop=True)
        y_pos = np.arange(len(top10))

        ax.barh(y_pos, top10["mean_test_score"],
                xerr=top10["std_test_score"],
                color=color, alpha=TUNED_ALPHA, linewidth=0,
                error_kw={"elinewidth": 0.7, "capsize": 2, "ecolor": "#555555"})

        ax.set_yticks(y_pos)
        ax.set_yticklabels([f"#{i+1}" for i in range(len(top10))], fontsize=6.5)
        ax.set_xlabel("CV AUC-ROC", fontsize=7)
        ax.set_title(f"{model}: top 10 hyperparameter candidates", fontsize=9)
        ax.invert_yaxis()

        # Mark the best
        ax.barh([0], [top10.loc[0, "mean_test_score"]], color=color,
                alpha=1.0, linewidth=0)

        ax.spines["left"].set_visible(False)
        ax.tick_params(left=False)

        # Tight x range around top10 scores
        all_vals = top10["mean_test_score"].values
        lo = max(0, all_vals.min() - 0.01)
        hi = min(1.0, all_vals.max() + 0.015)
        ax.set_xlim(lo, hi)

    for idx in range(n, len(axes)):
        axes[idx].set_visible(False)

    fig.suptitle("Top 10 hyperparameter combinations by CV AUC-ROC", fontsize=9)
    fig.tight_layout(rect=[0, 0, 1, 0.96])
    savefig(fig, "fig06_top10_candidates.pdf")


