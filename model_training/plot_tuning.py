def savefig(fig, name):
    os.makedirs(OUTDIR, exist_ok=True)
    path = os.path.join(OUTDIR, name.replace(".pdf", ".png"))
    fig.savefig(path, dpi=600)
    print(f"  Saved -> {path}")
    plt.close(fig)


def load_test_data():
    """Reproduce the same test split as tune.py (identical random_state)."""
    print("  Loading and splitting data...")
    pos_seqs, pos_ids = load_fasta_sequences(POSITIVE_FILE)
    neg_seqs, neg_ids = load_fasta_sequences(NEGATIVE_FILE)
    sequences = pos_seqs + neg_seqs
    ids       = pos_ids + neg_ids
    labels    = [1] * len(pos_seqs) + [0] * len(neg_seqs)

    features_df = calculate_physicochemical_features(sequences, ids)
    features_df["label"] = labels
    X = features_df.drop(columns=["ID", "sequence", "label"]).fillna(0)
    y = features_df["label"]

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=TEST_SIZE, random_state=RANDOM_STATE, stratify=y
    )
    scaler = StandardScaler()
    scaler.fit(X_train)
    X_test_sc = pd.DataFrame(
        scaler.transform(X_test), columns=X_test.columns, index=X_test.index
    )
    X_train_sc = pd.DataFrame(
        scaler.transform(X_train), columns=X_train.columns, index=X_train.index
    )
    return X_train_sc, X_test_sc, y_train, y_test


def load_tuned_models():
    models = {}
    for name in MODELS_ORDER:
        path = os.path.join(TUNED_DIR, f"amp_model_{name.lower()}_tuned.pkl")
        if os.path.exists(path):
            models[name] = joblib.load(path)
        else:
            print(f"  Warning: {path} not found, skipping {name}.")
    return models


def load_baseline_models():
    models = {}
    for name in MODELS_ORDER:
        path = os.path.join(SAVED_DIR, f"amp_model_{name.lower()}.pkl")
        if os.path.exists(path):
            models[name] = joblib.load(path)
    return models


def load_all_results():
    result_files = glob.glob(os.path.join(TUNED_DIR, "result_*.csv"))
    if not result_files:
        return None, None
    tuned = pd.concat([pd.read_csv(f) for f in result_files], ignore_index=True)
    if not os.path.exists(BASELINE_PATH):
        return tuned, None
    baseline = pd.read_csv(BASELINE_PATH)
    baseline = baseline.rename(columns={"f1_score": "f1"})
    return tuned, baseline


def load_cv_results(model_name):
    path = os.path.join(TUNED_DIR, f"cv_results_{model_name.lower()}.csv")
    if not os.path.exists(path):
        return None
    return pd.read_csv(path)


