# Fig 05 - Feature importance
# ---------------------------------------------------------------------------
def fig05_feature_importance(models, X_train, y_train, X_test, y_test):
    n = len(models)
    ncols = 2
    nrows = (n + 1) // 2
    fig, axes = plt.subplots(nrows, ncols, figsize=(COL2, nrows * 3.2))
    axes = np.array(axes).flatten()

    for idx, (name, model) in enumerate(models.items()):
        ax = axes[idx]
        color = COLORS[name]

        if hasattr(model, "feature_importances_"):
            importances = model.feature_importances_
            stds = np.zeros_like(importances)
        else:
            # Permutation importance for SVM
            print(f"  Computing permutation importance for {name} (may take ~1 min)...")
            result = permutation_importance(
                model, X_test, y_test,
                n_repeats=10, random_state=RANDOM_STATE, n_jobs=-1,
                scoring="roc_auc"
            )
            importances = result.importances_mean
            stds = result.importances_std

        order = np.argsort(importances)
        names_sorted = [FEATURE_NAMES[i] for i in order]
        imp_sorted   = importances[order]
        std_sorted   = stds[order]

        y_pos = np.arange(len(names_sorted))
        ax.barh(y_pos, imp_sorted, xerr=std_sorted if stds.any() else None,
                color=color, alpha=TUNED_ALPHA, linewidth=0,
                error_kw={"elinewidth": 0.7, "capsize": 2, "ecolor": "#555555"})
        ax.set_yticks(y_pos)
        ax.set_yticklabels(names_sorted, fontsize=6)
        ax.set_xlabel("Importance" if hasattr(model, "feature_importances_")
                      else "Permutation importance (AUC-ROC)", fontsize=7)
        ax.set_title(name, fontsize=9)
        ax.spines["left"].set_visible(False)
        ax.tick_params(left=False)

    # Hide unused axes if n is odd
    for idx in range(n, len(axes)):
        axes[idx].set_visible(False)

    fig.suptitle("Physicochemical feature importance per classifier", fontsize=9)
    fig.tight_layout(rect=[0, 0, 1, 0.96])
    savefig(fig, "fig04_feature_importance.pdf")


