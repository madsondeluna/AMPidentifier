# Fig 08-10 - Hyperparameter exploration scatter plots
# ---------------------------------------------------------------------------
def fig_hyperparam(model_name, param_cols, log_params, fig_num):
    cv = load_cv_results(model_name)
    if cv is None:
        print(f"  Skipping fig{fig_num:02d}: cv_results_{model_name}.csv not found.")
        return

    color     = COLORS[model_name.upper()]
    score_col = "mean_test_score"
    std_col   = "std_test_score"
    best_idx  = cv[score_col].idxmax()

    # Filter to numeric params only for scatter
    numeric_params = []
    for p in param_cols:
        col = f"param_{p}"
        if col in cv.columns:
            vals = pd.to_numeric(cv[col], errors="coerce")
            if vals.notna().sum() >= 5:
                numeric_params.append(p)

    if not numeric_params:
        print(f"  Skipping fig{fig_num:02d}: no numeric params found.")
        return

    n = len(numeric_params)
    fig, axes = plt.subplots(1, n, figsize=(COL1 * n, 2.6))
    if n == 1:
        axes = [axes]

    for ax, param in zip(axes, numeric_params):
        col  = f"param_{param}"
        vals = pd.to_numeric(cv[col], errors="coerce")
        mask = vals.notna()
        x    = vals[mask].values
        y    = cv.loc[mask, score_col].values
        yerr = cv.loc[mask, std_col].values

        ax.errorbar(x, y, yerr=yerr, fmt="o", color=color,
                    alpha=0.50, markersize=4, linewidth=0,
                    capsize=1.5, elinewidth=0.6, ecolor=color)

        # Highlight best candidate if it has a numeric value for this param
        if mask[best_idx]:
            ax.scatter([vals[best_idx]], [cv.loc[best_idx, score_col]],
                       color=color, s=45, zorder=5, linewidths=0, marker="*")

        if param in log_params:
            ax.set_xscale("log")

        ax.set_xlabel(param.replace("_", " "))
        ax.set_ylabel("CV AUC-ROC")
        ax.set_title(f"{model_name.upper()}: {param.replace('_', ' ')} vs. CV AUC-ROC",
                     fontsize=9)

    fig.suptitle(f"{model_name.upper()} — hyperparameter search space (star = selected optimum)",
                 fontsize=9, y=1.04)
    savefig(fig, f"fig{fig_num:02d}_hyperparam_{model_name.lower()}.pdf")


