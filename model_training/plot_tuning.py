# Fig 02 - ROC curves
# ---------------------------------------------------------------------------
def fig02_roc_curves(models, X_test, y_test):
    fig, ax = plt.subplots(figsize=(COL1, COL1))

    for name, model in models.items():
        y_proba = model.predict_proba(X_test)[:, 1]
        fpr, tpr, _ = roc_curve(y_test, y_proba)
        roc_auc = auc(fpr, tpr)
        ax.plot(fpr, tpr, color=COLORS[name], linewidth=1.2,
                label=f"{name} (AUC = {roc_auc:.3f})")

    ax.plot([0, 1], [0, 1], color="#aaaaaa", linewidth=0.8, linestyle="--")
    ax.set_xlim([-0.02, 1.02])
    ax.set_ylim([-0.02, 1.02])
    ax.set_xlabel("False positive rate")
    ax.set_ylabel("True positive rate")
    ax.set_title("Receiver operating characteristic (ROC) curves", fontsize=9)
    ax.legend(loc="lower right")

    savefig(fig, "fig01_roc_curves.pdf")


