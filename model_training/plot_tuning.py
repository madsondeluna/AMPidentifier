# Fig 01 - Performance comparison: baseline vs tuned
# ---------------------------------------------------------------------------
def fig01_performance_comparison(tuned, baseline):
    metrics = ["auc_roc", "mcc", "f1"]
    labels  = ["AUC-ROC", "MCC", "F1-score"]

    fig, axes = plt.subplots(1, 3, figsize=(COL2, 2.4))

    for ax, metric, label in zip(axes, metrics, labels):
        x     = np.arange(len(MODELS_ORDER))
        width = 0.35

        for i, model in enumerate(MODELS_ORDER):
            color = COLORS[model]
            if baseline is not None:
                brow = baseline[baseline["model"].str.upper() == model]
                if not brow.empty and metric in brow.columns:
                    ax.bar(x[i] - width / 2, float(brow[metric].values[0]),
                           width, color=color, alpha=BASELINE_ALPHA, linewidth=0)
            trow = tuned[tuned["model"].str.upper() == model]
            if not trow.empty and metric in trow.columns:
                ax.bar(x[i] + width / 2, float(trow[metric].values[0]),
                       width, color=color, alpha=TUNED_ALPHA, linewidth=0)

        ax.set_xticks(x)
        ax.set_xticklabels(MODELS_ORDER)
        ax.set_ylabel(label)
        ax.yaxis.set_major_locator(MaxNLocator(5, prune="lower"))

        all_vals = []
        for model in MODELS_ORDER:
            for df in [baseline, tuned]:
                if df is not None:
                    row = df[df["model"].str.upper() == model]
                    if not row.empty and metric in row.columns:
                        all_vals.append(float(row[metric].values[0]))
        if all_vals:
            ax.set_ylim(max(0, min(all_vals) - 0.03), min(1.0, max(all_vals) + 0.03))

    patch_base  = mpatches.Patch(color="gray", alpha=BASELINE_ALPHA, label="Baseline")
    patch_tuned = mpatches.Patch(color="gray", alpha=TUNED_ALPHA, label="Tuned")
    model_patches = [mpatches.Patch(color=COLORS[m], label=m) for m in MODELS_ORDER]
    axes[1].legend(handles=[patch_base, patch_tuned] + model_patches,
                   loc="lower center", bbox_to_anchor=(0.5, -0.34),
                   ncol=5, handlelength=1.2, handletextpad=0.5, columnspacing=0.8)

    fig.suptitle("Baseline vs. optimized hyperparameters", fontsize=9, y=1.02)
    savefig(fig, "fig01_performance_comparison.pdf")


