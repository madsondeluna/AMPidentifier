# Fig 11 - Metrics comparison: all models + ensemble
# ---------------------------------------------------------------------------
def fig11_metrics_comparison(models, X_test, y_test):
    from scipy.stats import mode as scipy_mode

    metrics_def = [
        ("accuracy",    "Accuracy"),
        ("precision",   "Precision"),
        ("recall",      "Sensitivity"),
        ("specificity", "Specificity"),
        ("f1",          "F1-score"),
        ("mcc",         "MCC"),
        ("auc_roc",     "AUC-ROC"),
    ]

    def compute_metrics(y_true, y_pred, y_proba):
        tn, fp, fn, tp = confusion_matrix(y_true, y_pred).ravel()
        return {
            "accuracy":    accuracy_score(y_true, y_pred),
            "precision":   precision_score(y_true, y_pred, zero_division=0),
            "recall":      recall_score(y_true, y_pred, zero_division=0),
            "specificity": tn / (tn + fp) if (tn + fp) > 0 else 0.0,
            "f1":          f1_score(y_true, y_pred, zero_division=0),
            "mcc":         matthews_corrcoef(y_true, y_pred),
            "auc_roc":     roc_auc_score(y_true, y_proba),
        }

    all_preds  = {}
    all_probas = {}
    results    = {}

    for name, model in models.items():
        y_pred  = model.predict(X_test)
        y_proba = model.predict_proba(X_test)[:, 1]
        all_preds[name]  = y_pred
        all_probas[name] = y_proba
        results[name]    = compute_metrics(y_test, y_pred, y_proba)

    # Ensemble: majority vote; mean proba for AUC-ROC
    if len(models) > 1:
        preds_matrix = np.column_stack(list(all_preds.values()))
        ensemble_pred, _ = scipy_mode(preds_matrix, axis=1, keepdims=True)
        ensemble_pred    = ensemble_pred.ravel().astype(int)
        ensemble_proba   = np.mean(list(all_probas.values()), axis=0)
        results["Ensemble"] = compute_metrics(y_test, ensemble_pred, ensemble_proba)

    model_names = list(results.keys())
    ensemble_color = "#555555"
    colors = [COLORS.get(m, ensemble_color) for m in model_names]

    n_metrics = len(metrics_def)
    n_models  = len(model_names)
    x         = np.arange(n_metrics)
    total_width = 0.75
    bar_width   = total_width / n_models

    fig, ax = plt.subplots(figsize=(COL2, 3.0))

    for i, (name, color) in enumerate(zip(model_names, colors)):
        vals = [results[name][key] for key, _ in metrics_def]
        offset = (i - (n_models - 1) / 2) * bar_width
        alpha  = 1.0 if name == "Ensemble" else TUNED_ALPHA
        ax.bar(x + offset, vals, bar_width,
               color=color, alpha=alpha, linewidth=0, label=name)

    ax.set_xticks(x)
    ax.set_xticklabels([lbl for _, lbl in metrics_def], fontsize=7)
    ax.set_ylabel("Score")
    ax.set_ylim(0, 1.08)
    ax.yaxis.set_major_locator(MaxNLocator(6, prune="upper"))

    # Reference threshold line at 90%
    ax.axhline(0.90, color="#b22222", linewidth=0.9, linestyle="--", zorder=0)
    ax.text(-0.55, 0.90 + 0.008, "90%",
            color="#b22222", fontsize=6.5, va="bottom", ha="left")

    legend_patches = [
        mpatches.Patch(color=COLORS.get(m, ensemble_color),
                       alpha=1.0 if m == "Ensemble" else TUNED_ALPHA, label=m)
        for m in model_names
    ]
    ax.legend(handles=legend_patches,
              loc="upper center", bbox_to_anchor=(0.5, -0.13),
              ncol=n_models, handlelength=1.0,
              handletextpad=0.4, columnspacing=0.7)

    ax.set_title("Classification performance across tuned models and ensemble vote",
                 fontsize=9)
    fig.tight_layout(rect=[0, 0.08, 1, 1])
    savefig(fig, "fig11_metrics_comparison.pdf")


